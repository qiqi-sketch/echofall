bool Font::init(SDL_Renderer* ren) {
    ensureIndex();
    int rows = (kGlyphCount + kCols - 1) / kCols;
    int texW = kCols * kCellW;
    int texH = rows * kCellH;
    tex_ = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_TARGET, texW, texH);
    if (!tex_) return false;

    SDL_SetTextureBlendMode(tex_, SDL_BLENDMODE_BLEND);
    SDL_SetRenderTarget(ren, tex_);
    SDL_SetRenderDrawColor(ren, 0, 0, 0, 0);
    SDL_RenderClear(ren);
    SDL_SetRenderDrawColor(ren, 255, 255, 255, 255);
    SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_BLEND);
    for (int i = 0; i < kGlyphCount; ++i) {
        int gx = (i % kCols) * kCellW;
        int gy = (i / kCols) * kCellH;
        for (int row = 0; row < 7; ++row) {
            const char* line = kGlyphs[i].rows[row];
            for (int col = 0; col < 5; ++col) {
                if (line[col] == '#') {
                    SDL_Rect r{gx + col * 2, gy + row * 2, 2, 2};
                    SDL_RenderFillRect(ren, &r);
                }
            }
        }
    }
    SDL_SetRenderTarget(ren, nullptr);
    SDL_SetTextureScaleMode(tex_, SDL_ScaleModeNearest);
    return true;
}

void Font::destroy() {
    if (tex_) {
        SDL_DestroyTexture(tex_);
        tex_ = nullptr;
    }
}

void Font::draw(SDL_Renderer* ren, const std::string& text, float x, float y, float height,
                SDL_Color color) const {
    if (!tex_ || height <= 0.0f) return;
    float scale = height / 7.0f;
    float advance = 6.0f * scale;
    float gw = 5.0f * scale;
    SDL_SetTextureColorMod(tex_, color.r, color.g, color.b);
    SDL_SetTextureAlphaMod(tex_, color.a);
    float cx = x;
    for (char ch : text) {
        unsigned char uc = (unsigned char)ch;
        int idx = (uc < 128) ? gIndex[uc] : -1;
        if (idx >= 0) {
            SDL_Rect src{(idx % kCols) * kCellW, (idx / kCols) * kCellH, kCellW, kCellH};
            SDL_FRect dst{cx, y, gw, height};
            SDL_RenderCopyF(ren, tex_, &src, &dst);
        }
        cx += advance;
    }
}

float Font::width(const std::string& text, float height) const {
    float scale = height / 7.0f;
    return (float)text.size() * 6.0f * scale - scale;
}

