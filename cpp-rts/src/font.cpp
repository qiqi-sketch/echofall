constexpr int kGlyphCount = (int)(sizeof(kGlyphs) / sizeof(kGlyphs[0]));
constexpr int kCols = 16;
constexpr int kCellW = 10;
constexpr int kCellH = 14;

int gIndex[128];
bool gIndexReady = false;

void ensureIndex() {
    if (gIndexReady) return;
    for (int i = 0; i < 128; ++i) gIndex[i] = -1;
    for (int i = 0; i < kGlyphCount; ++i) {
        unsigned char c = (unsigned char)kGlyphs[i].c;
        gIndex[c] = i;
        if (c >= 'A' && c <= 'Z') {
            gIndex[c - 'A' + 'a'] = i;
        }
    }
    gIndexReady = true;
}

